let language = 'zh-CN';
export function setLanguage(value) {
  if (!['zh-CN', 'en'].includes(value)) throw new Error('Unsupported language');
  language = value;
}
export function getLanguage() { return language; }
export function t(source, values = {}) {
  const template = language === 'en' ? (english[source] ?? source) : source;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}
export function errorText(error) {
  let message = String(error);
  if (language !== 'en') return message;
  for (const [source, translated] of Object.entries({ ...english, ...nativeErrors }).sort((first, second) => second[0].length - first[0].length)) message = message.replaceAll(source, translated);
  return message.replaceAll('：', ': ');
}
export function message(node, source, values = {}) {
  delete node.dataset.errorSource;
  node.dataset.i18n = source;
  node.dataset.i18nValues = JSON.stringify(values);
  node.textContent = t(source, values);
}
export function errorMessage(node, error) {
  delete node.dataset.i18n;
  node.dataset.errorSource = String(error);
  node.textContent = errorText(error);
}
export function translatePage(root = document) {
  document.documentElement.lang = language;
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n, JSON.parse(node.dataset.i18nValues || '{}'));
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-label]')) node.setAttribute('aria-label', t(node.dataset.i18nLabel));
  for (const node of root.querySelectorAll('[data-error-source]')) node.textContent = errorText(node.dataset.errorSource);
}
